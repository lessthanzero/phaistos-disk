# 7 Bronze Age Cretan Ecological Domains
DOMAINS = [
    "DIVINE_SKY",
    "HUMAN_SOCIAL",
    "AGRICULTURAL_LAND",
    "FLORA",
    "FAUNA",
    "MARINE_WATER",
    "CRAFT_TRADE",
]

DOMAIN_DESCRIPTIONS = {
    "DIVINE_SKY": "Celestial, epiphany, solar, and sacred symbols (Raptors, Rosette, Water/Snake, Plumed Priest).",
    "HUMAN_SOCIAL": "Human actors, gender roles, athletic games, captives, and body modifications.",
    "AGRICULTURAL_LAND": "Cultivated plain tools, hunting weapons, apiculture, granaries, and defensive shields.",
    "FLORA": "Managed trees, vine cultivation, sacred sedges, lilies, and crop branches.",
    "FAUNA": "Domesticated livestock (cattle, sheep), native wildcats, birds, and animal pelts.",
    "MARINE_WATER": "Maritime economy, Libyan Sea pelagic tuna, galleys, navigation, and coastal resources.",
    "CRAFT_TRADE": "Pyrotechnology, ceramics, carpentry tools, weaving combs, strainers, and architectural pillars.",
}


def evaluate_ecological_constraints(corpus: DiscCorpus) -> EcologicalConstraintResult:
    """Evaluate all 45 signs and their corpus tokens against Bronze Age Cretan ecology."""
    all_tokens = [s for g in corpus.all_groups() for s in g.signs]
    token_counts = Counter(all_tokens)

    domain_signs = {d: [] for d in DOMAINS}
    domain_token_counts = {d: 0 for d in DOMAINS}

    for sign_id, profile in ECOLOGICAL_CATALOGUE.items():
        dom = profile["domain"]
        domain_signs[dom].append(sign_id)
        domain_token_counts[dom] += token_counts.get(sign_id, 0)

    total_tokens = len(all_tokens)

    domain_summaries: List[EcologicalDomainSummary] = []
    for d in DOMAINS:
        t_cnt = domain_token_counts[d]
        pct = (t_cnt / float(total_tokens)) * 100.0 if total_tokens > 0 else 0.0
        domain_summaries.append(
            EcologicalDomainSummary(
                domain=d,
                sign_count=len(domain_signs[d]),
                token_count=t_cnt,
                share_of_corpus_pct=round(pct, 1),
                key_signs=sorted(domain_signs[d]),
                ecological_description=DOMAIN_DESCRIPTIONS[d],
            )
        )

    flora_count = len(domain_signs["FLORA"])
    fauna_count = len(domain_signs["FAUNA"])
    marine_count = len(domain_signs["MARINE_WATER"])

    # Anthropogenic landscape score: proportion of signs reflecting human-managed ecosystem
    # (Humans, agricultural land, managed flora, domestic fauna, crafts vs pure wild wilderness)
    anthropogenic_domains = {"HUMAN_SOCIAL", "AGRICULTURAL_LAND", "FLORA", "CRAFT_TRADE"}
    anthro_tokens = sum(domain_token_counts[d] for d in anthropogenic_domains)
    anthro_score = (anthro_tokens / float(total_tokens)) * 100.0 if total_tokens > 0 else 0.0

    # Bayesian confidence mean
    confidences = [p["confidence"] for p in ECOLOGICAL_CATALOGUE.values()]
    mean_conf = float(np.mean(confidences))

    # Falsification audit summary
    falsifications = []
    for sign_id, p in ECOLOGICAL_CATALOGUE.items():
        if p["falsifications"]:
            for f in p["falsifications"]:
                falsifications.append({
                    "sign_id": sign_id,
                    "name": p["name"],
                    "falsified_claim": f,
                })

    verdict = (
        f"ECOLOGICAL & GEOGRAPHIC CONSTRAINT AUDIT:\n"
        f"1. Anthropogenic Landscape: {anthro_score:.1f}% of signs encode managed agro-pastoral, "
        f"craft, and social activities of Middle Minoan Crete (olives, vines, cereals, sheep, cattle, "
        f"beekeeping, tuna fishing), rather than undomesticated wilderness.\n"
        f"2. Local Ecological Falsifications: Wild Egyptian papyrus (*Cyperus papyrus*) and African lions "
        f"are falsified in favor of native Cretan sweet galingale (*Cyperus longus*, Tablet PH 1 line 2) "
        f"and endemic Cretan wildcats (*Felis lybica cretensis*).\n"
        f"3. Bayesian Plausibility: Mean sign ecological plausibility score = {mean_conf*100:.1f}%. "
        f"The visual vocabulary represents a coherent Bronze Age Cretan cosmos spanning Divine, "
        f"Agro-Pastoral, Maritime, and Palatial Craft domains."
    )

    return EcologicalConstraintResult(
        total_signs_analyzed=len(ECOLOGICAL_CATALOGUE),
        domain_distribution=domain_summaries,
        flora_signs_count=flora_count,
        fauna_signs_count=fauna_count,
        marine_signs_count=marine_count,
        anthropogenic_landscape_score=round(anthro_score, 1),
        bayesian_mean_confidence=round(mean_conf, 3),
        falsification_audit=falsifications,
        skeptic_verdict=verdict,
    )
